
-- ==========================================
-- ORANGE FIBRE - BASE DE DONNEES
-- PostgreSQL
-- ==========================================

-- 1. UTILISATEURS
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100),
    email VARCHAR(150) NOT NULL UNIQUE,
    telephone VARCHAR(20),
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'client'
        CHECK (role IN ('admin', 'client', 'agent')),
    actif BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. CLIENTS
CREATE TABLE IF NOT EXISTS clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE REFERENCES users(id) ON DELETE SET NULL,
    adresse VARCHAR(255) NOT NULL,
    commune VARCHAR(100),
    ville VARCHAR(100) DEFAULT 'Abidjan',
    numero_piece VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 3. OFFRES FIBRE
CREATE TABLE IF NOT EXISTS offres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    description TEXT,
    debit_mbps INTEGER NOT NULL CHECK (debit_mbps > 0),
    prix_mensuel NUMERIC(12,2) NOT NULL CHECK (prix_mensuel >= 0),
    frais_installation NUMERIC(12,2) DEFAULT 0,
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 4. SOUSCRIPTIONS
CREATE TABLE IF NOT EXISTS souscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    offre_id BIGINT NOT NULL REFERENCES offres(id),
    adresse_installation VARCHAR(255) NOT NULL,
    commune VARCHAR(100),
    statut VARCHAR(30) DEFAULT 'en_attente'
        CHECK (statut IN (
            'en_attente',
            'en_etude',
            'acceptee',
            'rejetee',
            'en_installation',
            'terminee',
            'annulee'
        )),
    date_souscription TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    date_installation DATE,
    observations TEXT
);

-- 5. ACTUALITES ET PROMOTIONS
CREATE TABLE IF NOT EXISTS actualites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    contenu TEXT NOT NULL,
    image VARCHAR(255),
    categorie VARCHAR(100),
    publie BOOLEAN DEFAULT FALSE,
    date_publication TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 6. RECLAMATIONS
CREATE TABLE IF NOT EXISTS reclamations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    souscription_id BIGINT REFERENCES souscriptions(id)
        ON DELETE SET NULL,
    sujet VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    statut VARCHAR(30) DEFAULT 'ouverte'
        CHECK (statut IN ('ouverte', 'en_cours', 'resolue', 'fermee')),
    reponse TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 7. INDEX POUR LES RECHERCHES
CREATE INDEX IF NOT EXISTS idx_souscriptions_client
    ON souscriptions(client_id);

CREATE INDEX IF NOT EXISTS idx_souscriptions_statut
    ON souscriptions(statut);

CREATE INDEX IF NOT EXISTS idx_reclamations_client
    ON reclamations(client_id);

CREATE INDEX IF NOT EXISTS idx_actualites_publication
    ON actualites(publie, date_publication);

-- 8. DROITS DE L'APPLICATION
GRANT USAGE ON SCHEMA public TO orange_app;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON ALL TABLES IN SCHEMA public TO orange_app;

GRANT USAGE, SELECT, UPDATE
    ON ALL SEQUENCES IN SCHEMA public TO orange_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO orange_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO orange_app;
